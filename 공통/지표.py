"""지표마다 함수 1개: s → 종목별 값(Series). 공식대로 계산한 값 그대로(분모가 0 이하여도 손대지 않음).
s["fin"] = 그날 쓸 수 있는 회계연도 재무(천원, 열=아이템코드), s["mcap"] = 시가총액(백만원), s["ret"] = 직전 12개월 일간수익률.
비율 지표(PBR·PER·PSR·POCF·EV/EBITDA)는 적자·자본잠식 종목이 '싼 쪽'으로 줄 서지 않도록 역수(수익률 꼴)로 둔다 → 방향 '높게'."""
import numpy as np
import pandas as pd

import 데이터읽기 as 읽기

# 세전이익 = 세전계속사업이익(K-IFRS 법인세비용차감전순이익은 계속사업 기준, 중단사업손익은 세후로 따로 표시 → 들어가지 않음)
세전이익, 이자비용, 무형자산 = "M000907001", "M000906020", "M000901024"

유동자산, 현금, 유동부채, 영업이익 = "M000901002", "M000901030", "M000902003", "M000906001"
자산, 매출, 매출원가, 지배순이익, 부채, 자본, 지배자본 = "M000901001", "M000904001", "M000905001", "M000908004", "M000902001", "M000903001", "M000903003"
영업CF, EBITDA_, 순이익, 매출총이익 = "M000909001", "M000701032", "M000908001", "M000904007"


# 판본마다 값이 달라 어느 쪽도 고르지 않는 칸 → 그 회계연도에 빈칸으로 본다(값은 그대로). 호텔신라 FY2023 매출원가·매출총이익(R29, 통합_확인기록 F1, 회원 결정 2026-11-02)
빈칸으로볼칸 = {("A008770", 2023): {"M000905001", "M000904007"}}


def 값(s, code):
    x = s["fin"][code]
    bad = [c for (c, y), items in 빈칸으로볼칸.items() if code in items and s["fin"]["회계연도"].get(c) == y]
    return x.mask(x.index.isin(bad))


def 기업가치(s):
    """우동호 외(2023) 3.2절: 시가총액 + 부채총액 − 현금 (천원)."""
    return s["mcap"] * 1000 + 값(s, 부채) - 값(s, 현금)


# 마법공식
def EBIT(s):
    """우동호 외(2023) 3.2절 ②: 법인세차감전이익 + 이자비용."""
    return 값(s, 세전이익) + 값(s, 이자비용)


def BP_장부원문_6개월(s):
    """Novy-Marx(2010) 각주 3 장부가 = 자본 + 이연법인세 − 우선주: 자본총계(지배) + 이연법인세부채(M000911019) − 우선주자본금(M000903008),
    시가는 6개월 전 시가총액(BP_6개월과 같음). 원문(PDF 13쪽 각주 3) 'plus deferred taxes, minus preferred stock, when available' → 이연법인세·우선주 값이 빈 종목은 그 항만 뺌(0으로 셈).
    자본총계(지배)는 Compustat SEQ(우선주 포함 주주지분)에 가장 가까운 항목으로 고름(같은지는 확인 안 함). 두 항목 파일이 없으면 빈칸(04 진단용, 추가 지시 F)."""
    if not {"M000911019", "M000903008"} <= set(s["fin"]):
        return pd.Series(np.nan, s["codes"])
    m = 읽기.일간(읽기.시총).loc[:s["t"] - pd.DateOffset(months=6)].iloc[-1].reindex(s["codes"])
    return (값(s, 지배자본) + 값(s, "M000911019").fillna(0) - 값(s, "M000903008").fillna(0)) / (m * 1000)


def EY(s):
    return EBIT(s) / 기업가치(s)


def 투하자본(s):
    return 값(s, 유동자산) - 값(s, 유동부채) + 값(s, 자산) - 값(s, 무형자산)


def ROC(s):
    """우동호 외(2023): EBIT / (유동자산 − 유동부채 + 총자산 − 무형자산)."""
    return EBIT(s) / 투하자본(s)


def EBIT_잠정(s):
    """01 확인판(추가 지시 F, 회원 결정 2026-11-04 15:13): 세전이익 = 세전계속사업이익 잠정치(FP56000300), 이자비용 = 지금 값(최초치 없음).
    잠정치가 없는 종목은 빈칸(확정치로 채우면 종목마다 다른 시점 값이 섞임, `_검증/추가로_받을것.md` 9절). 파일이 없으면 전부 빈칸."""
    if "FP56000300" not in s["fin"]:
        return pd.Series(np.nan, s["codes"])
    return 값(s, "FP56000300") + 값(s, 이자비용)


def EY_잠정(s):
    return EBIT_잠정(s) / 기업가치(s)


def ROC_잠정(s):
    return EBIT_잠정(s) / 투하자본(s)


def GPA(s):
    """우동호 외(2023) p.513 IMF: 매출총이익 / 총자산(Novy-Marx 2013 GP/A: 매출총이익 = 매출액 − 매출원가). 매출총이익 M000904007."""
    return 값(s, 매출총이익) / 값(s, 자산)


# 밸류 (역수 꼴)
def BP(s):
    """PBR 역수: 자본총계(지배) / 시가총액."""
    return 값(s, 지배자본) / (s["mcap"] * 1000)


def BP_6개월(s):
    """BP의 시가총액을 6개월 전(그날 또는 그 전 마지막 거래일) 값으로. Novy-Marx(2010) 각주 3 'lagged six months'(04 진단용)."""
    m = 읽기.일간(읽기.시총).loc[:s["t"] - pd.DateOffset(months=6)].iloc[-1].reindex(s["codes"])
    return 값(s, 지배자본) / (m * 1000)


def EP(s):
    """PER 역수: 당기순이익(지배) / 시가총액."""
    return 값(s, 지배순이익) / (s["mcap"] * 1000)


def SP(s):
    """PSR 역수: 매출액 / 시가총액."""
    return 값(s, 매출) / (s["mcap"] * 1000)


def CFP(s):
    """POCF 역수: 영업활동현금흐름 / 시가총액."""
    return 값(s, 영업CF) / (s["mcap"] * 1000)


def EBITDA_EV(s):
    """EV/EBITDA 역수: EBITDA / 기업가치."""
    return 값(s, EBITDA_) / 기업가치(s)


def EBITDA_EV_차입금(s):
    """02 확인판(회원 결정 2026-11-04 15:51): EV = 시가총액 + 단기차입금(M000902009) + 유동성장기부채(M000902044) − 현금. NH 밸류 원문에 EV 정의가 없어
    본문 EV(시총 + 부채총계 − 현금)는 그대로 두고 비교만. 두 항목은 결산 파일뿐이라 연간 재무로만 돈다. 빈칸은 빈칸(0으로 안 채움)."""
    return 값(s, EBITDA_) / (s["mcap"] * 1000 + 값(s, "M000902009") + 값(s, "M000902044") - 값(s, 현금))


def 영업이익_EV(s):
    """EV/영업이익 역수(칼라일 '인수자 배수'): 영업이익(발표기준) M000906002 / 기업가치."""
    return 값(s, "M000906002") / 기업가치(s)


# 퀄리티
def ROE(s):
    return 값(s, 지배순이익) / 값(s, 지배자본)


def ROE_양자본(s):
    """확인판: 지배자본 > 0인 종목만(자본이 음수면 ROE 부호가 뒤집혀 좋은 쪽에 줄 섬). 값은 그대로."""
    return ROE(s).where(값(s, 지배자본) > 0)


def ROA(s):
    """당기순이익(연결 전체, M000908001) / 자산총계."""
    return 값(s, 순이익) / 값(s, 자산)


def 영업CF자산(s):
    """영업활동현금흐름 / 자산총계(현금 기준 수익성)."""
    return 값(s, 영업CF) / 값(s, 자산)


def 영업이익률(s):
    return 값(s, 영업이익) / 값(s, 매출)


def 부채비율(s):
    return 값(s, 부채) / 값(s, 자본)


def 부채비율_양자본(s):
    """확인판: 자본총계 > 0인 종목만."""
    return 부채비율(s).where(값(s, 자본) > 0)


def 총자산회전율(s):
    return 값(s, 매출) / 값(s, 자산)


# 위험
def 일년상장(s):
    """직전 12개월 내내 시장구분이 코스피·코스닥이던 종목(F2: 상장일은 이전상장 전 날짜라 쓰지 않음, 코드 재사용 공백도 여기서 걸림)."""
    return s["일년상장"]


def 변동성(s):
    """NH(2018-10): 직전 12개월 일간수익률 표준편차. 원문에 최소 관측 기준이 없어 12개월 내내 상장된 종목만. 기간 안 빈칸은 빼고 계산."""
    return s["ret"].std().where(일년상장(s))


def 변동성_창(s, 개월=12, 주기="일"):
    """NH(2018-10) p.23 그림 33·34: 직전 '개월' 동안 일간('일')·주간('주', 금요일 끝)·월간('월', 월말) 수익률 표준편차.
    변동성()과 같은 규칙: 창 내내 시장구분이 코스피·코스닥이고 창 첫날 상장 가격이 있는 종목만, '쓰지 말 것' 칸은 빈칸. 개월=12·주기='일'이면 변동성()과 같은 값."""
    t, c = s["t"], s["codes"]
    a = t - pd.DateOffset(months=개월)
    p = 읽기.상장가격(s["가격"]).loc[a:t, c].copy()
    for k, x, y in 읽기.쓰지말것(s["가격"])[["코드", "시작", "끝"]].itertuples(index=False):
        if k in p:
            p.loc[x:y, k] = np.nan
    ok = 읽기.상장중().loc[a:t].reindex(columns=c, fill_value=False).all() & p.iloc[0].notna()
    if 주기 != "일":
        p = p.resample({"주": "W-FRI", "월": "ME"}[주기]).last()
    return p.pct_change(fill_method=None).iloc[1:].std().where(ok)


# 우동호 외(2023) p.513 요인(원문대로 직접 만듦, 포트폴리오.원문요인)
def 시가총액(s):
    """SMB용: 그날 시가총액(백만원). '낮게' = 소형이 Q1."""
    return s["mcap"]


def 모멘텀11(s):
    """MOM용: 과거 11개월 수익률 = 그날 가격 / 11개월 전(그날 또는 그 전 마지막 거래일) 가격 − 1(우동호 p.513 '과거 11개월 동안 수익률', 건너뛰는 달은 원문에 없어 안 둠)."""
    p = 읽기.상장가격(s["가격"]).loc[:s["t"], s["codes"]]
    return p.iloc[-1] / p.loc[:s["t"] - pd.DateOffset(months=11)].iloc[-1] - 1


# 애널리스트 추정치(NH 2018-07 p.19 그림 25·26)
def EP_선행(s):
    """12개월 선행 E/P = 12개월 선행 EPS / 수정주가. 12개월 선행 EPS = FY1 × (12 − m)/12 + FY2 × m/12, m = 그날의 월(12월 결산 기준, FY1은 1월 초에 그해로 바뀜:
    삼성전자 2015-01-08 확인). 추정치는 DataGuide '최근 3개월' 컨센서스(원문 '애널리스트의 최근 3개월 EPS 추정치'). FY1·FY2 중 하나라도 없으면 빈칸."""
    t, c = s["t"], s["codes"]
    f1, f2 = (읽기.컨센서스(k).loc[:t].iloc[-1].reindex(c) for k in ("EPS_FY1", "EPS_FY2"))
    m = t.month
    return (f1 * (12 - m) / 12 + f2 * m / 12) / 읽기.일간(읽기.수정주가).loc[:t].iloc[-1].reindex(c)
