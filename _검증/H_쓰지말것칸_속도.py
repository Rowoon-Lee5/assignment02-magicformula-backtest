def 같은가(a, b):
    a, b = a.align(b, join="outer")
    na = a.isna().to_numpy() != b.isna().to_numpy()
    return float(np.nanmax(np.abs(a.to_numpy(float) - b.to_numpy(float)), initial=0)), int(na.sum()), a.shape


