# ## 애널리스트 추정치 P/E (원문 p.19 그림 25, p.20 그림 26)
# 원문 p.19 "2) 애널리스트 추정치 사용": "이에 동일한 로직으로 확정치가 아닌 애널리스트의 최근 3개월 EPS 추정치를 사용해 매월 리밸런싱하는 밸류 포트폴리오의 성과를 점검했다.
# 3개월 이내 애널리스트 추정치가 존재하는 종목의 수가 대략 300개 정도로 총 3개 그룹으로 구분해 상위 1/3 Long, 하위 1/3 Short 포트폴리오의 성과로 분석했다."
#
# | 항목 | 원문 | 쪽 | 우리 |
# |---|---|---|---|
# | 추정치 | 애널리스트의 최근 3개월 EPS 추정치 | 19 | DataGuide 컨센서스 '3개월' EPS(지배) FY1·FY2(`읽기.컨센서스`, FM30011505 R17·R18) |
# | 지표 | 그림 25·26 범례 '12개월 Fwd P/E' | 19·20 | 역수 꼴 `EP_선행` = 12개월 선행 EPS / 수정주가(본문 P/E도 역수 꼴 E/P라 같은 꼴) |
# | 12개월 선행 계산 | 원문에 없음 | — | FY1 × (12 − m)/12 + FY2 × m/12(`지표.EP_선행`) |
# | 묶음 | 3개 그룹, 상위 1/3 Long·하위 1/3 Short(그림 25 제목 '1분위 Long, 3분위 Short') | 19 | `고르기=("분위", 3)`, LS = Q1 − Q3 |
# | 유니버스 | '동일한 로직' + 3개월 이내 추정치가 있는 종목 | 19 | 본문 `기본` 거르기 뒤 FY1·FY2 추정치가 모두 있는 종목(없으면 그 달 제외) |
# | 리밸런싱 | 매월 | 19 | 본문과 같음(월말, 1개월) |
# | 그림 25 기간 | 가로축 '10.1~'18 | 19 | 2010-01 말 첫 리밸런싱 ~ 본문 끝(7절 현실판 '09.1과 같은 읽기). 본문 실행에서 2010-02 수익률부터 자름(매월 리밸런싱·비용 0이라 2010-01부터 따로 돌린 것과 같음) |
# | 그림 26 기간 | "2002년 이후", 가로축 '02.4~ | 19·20 | 본문 기간 |
# | 그림 26 묶음 | 상위 1/3 Long Only 동일가중 | 19 | Q1, 동일가중 |
# | 비교선 'P/E' | 확정 P/E(그림 25·26 범례 'P/E') | 19·20 | 본문 `EP`(발표 재무), 같은 3분위. 유니버스는 본문 전체(원문 p.19 "추정치가 존재하는 종목 수가 제한적"이 확정 P/E 쪽이 더 넓다는 뜻으로 읽음) |
#
# 원문 판정(방향·크기만): ① 그림 25 "P/E 지표를 이용한 밸류 포트폴리오가 2014년 이후 성과가 부진했던 것과 달리 애널리스트 추정치 P/E를 사용할 경우 꾸준히 효과적이었다"(p.19)
# ② 그림 26 "2002년 이후 상위 1/3 Long Only 동일가중 포트폴리오 누적 수익률에서 확정 P/E를 사용하는 데에 비해 크게 못 미쳤다"(p.19) ③ "3개월 이내 애널리스트 추정치가 존재하는 종목의 수가 대략 300개"(p.19).

# %%
# 시험(FOLLOW_TEST=1)이면 1절에서 평가.결과폴더가 _검증\1106\시험결과\로 바뀌어 있음
추정 = 포.실행({**기본, "지표": [("EP_선행", "높게")], "고르기": ("분위", 3)})
확정 = 포.실행({**기본, "지표": [("EP", "높게")], "고르기": ("분위", 3)})
q3 = lambda o: o["수익률"]["동일"]
LS3 = pd.DataFrame({"12개월 Fwd P/E": q3(추정)["Q1"] - q3(추정)["Q3"], "P/E": q3(확정)["Q1"] - q3(확정)["Q3"]})
Q1_3 = pd.DataFrame({"12개월 Fwd P/E": q3(추정)["Q1"], "P/E": q3(확정)["Q1"]})
추정수 = 추정["기록"][["편입:Q1", "편입:Q2", "편입:Q3"]].sum(axis=1)  # 그 달 추정치가 있어 3분위에 들어간 종목 수
print("추정치 종목 수(리밸런싱마다):", 추정수.describe().round(1).to_dict(), "/ 첫 리밸런싱", f"{추정수.index[0]:%Y-%m-%d}", int(추정수.iloc[0]))
시작25 = "2010-02" if not 시험 else LS3.index[0]  # 시험(짧은 기간)은 2010년 전이라 전체 구간
LS25 = LS3.loc[시작25:]
평가.누적그림(LS25, "그림 25: 12개월 Fwd P/E와 P/E, 1분위 Long·3분위 Short", 퍼센트=True);
평가.누적그림(Q1_3.dropna(how="all"), "그림 26: 12개월 Fwd P/E와 P/E, 상위 1/3 Long Only 동일가중", 퍼센트=True);

# %%
누25 = (1 + LS25).prod() - 1
후 = LS25.loc["2014":]  # 원문 '2014년 이후'
누후 = (1 + 후).prod() - 1
누26 = (1 + Q1_3).prod() - 1
대조25_26 = pd.DataFrame([
    ["p.19 그림 25", "애널리스트 추정치 P/E LS는 꾸준히 효과적", "(우리가 읽은 기준) 12개월 Fwd P/E LS 누적 > 0",
     f"Fwd {누25['12개월 Fwd P/E']:.3f} ({LS25.index[0]:%Y-%m}~{LS25.index[-1]:%Y-%m})", "같음" if 누25["12개월 Fwd P/E"] > 0 else "다름"],
    ["p.19 그림 25", "P/E는 2014년 이후 부진, 추정치 P/E는 달리 효과적", "(우리가 읽은 기준) 2014-01~ LS 누적: Fwd > 0이고 Fwd > P/E",
     f"2014~ Fwd {누후['12개월 Fwd P/E']:.3f}, P/E {누후['P/E']:.3f}" if len(후) else "구간 없음(시험 기간)",
     ("같음" if 누후["12개월 Fwd P/E"] > 0 and 누후["12개월 Fwd P/E"] > 누후["P/E"] else "다름") if len(후) else "판정 안 함"],
    ["p.19 그림 26", "상위 1/3 Long Only 누적: 추정치 P/E가 확정 P/E에 크게 못 미침", "Fwd Q1 누적 < P/E Q1 누적(크기는 두 누적을 그대로 적음)",
     f"Fwd {누26['12개월 Fwd P/E']:.3f}, P/E {누26['P/E']:.3f} ({Q1_3.dropna(how='all').index[0]:%Y-%m}~{Q1_3.index[-1]:%Y-%m})",
     "같음" if 누26["12개월 Fwd P/E"] < 누26["P/E"] else "다름"],
    ["p.19", "3개월 이내 추정치가 있는 종목 수 대략 300개", "(우리가 읽은 기준) 리밸런싱마다 종목 수 평균을 백 단위로 반올림하면 300",
     f"평균 {추정수.mean():.1f}, 최소 {추정수.min()}, 최대 {추정수.max()}", "같음" if round(추정수.mean(), -2) == 300 else "다름"],
], columns=["원문 쪽·그림", "원문 결론", "판정 기준", "우리", "판정"])
대조25_26.to_csv(평가.결과폴더 /"02_원문대조_그림25_26.csv", encoding="utf-8-sig")
