code1 = '''# (1) 주장 1·2를 지표마다, 판마다(본문 / 재무 180일 / 발표 당일부터 / 자본>0만)
def 지표판정(r):
    누 = (1 + r).prod() - 1
    중, 끝 = 누[["Q2", "Q3", "Q4"]].idxmax(), 누[["Q1", "Q5"]].idxmax()
    아래 = 누.drop("Q5").idxmin()
    p1, p2 = 평가.평균차이(r[중], r[끝])["p"], 평가.평균차이(r["Q5"], r[아래])["p"]
    판 = lambda ok, p: "경계" if p > 0.05 else ("같음" if ok else "다름")
    return {**{f"누적 {g}": 누[g] for g in 누.index}, "주장1: 중간 최고 대 끝 최고": f"{중} 대 {끝}", "주장1 p": p1, "주장1 판정": 판(누[중] > 누[끝], p1),
            "주장2: Q5 대 나머지 최저": f"Q5 대 {아래}", "주장2 p": p2, "주장2 판정": 판(누["Q5"] < 누[아래], p2)}
당일 = {n: 포.실행({**기본, "지표": [m], "재무시점": ("발표당일", 150)}) for n, m in 지표들.items() if n != "로우볼"}
양자본 = {n: 포.실행({**기본, "지표": [(f"{n}_양자본", 지표들[n][1])]}) for n in ["ROE", "부채비율"]}
판들 = {"본문": 결과, "재무 180일": 늦게, "발표 당일부터": 당일, "자본>0만": 양자본}
지표별 = pd.concat({k: pd.DataFrame({n: 지표판정(o["수익률"]["동일"]) for n, o in res.items() if n != "로우볼"}).T for k, res in 판들.items()})
지표별'''

