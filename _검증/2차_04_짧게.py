"""2차 진단 4 지시 J 짧은 시험: 02·03 본문 설정(재무시점 '발표월말')으로 앞 3년 + 마지막 2년을 돌려 오류 없는지, '발표일' 대비 바뀐 칸 수.
공통 폴더에서 PYTHONPATH=. python ../_검증/2차_04_짧게.py > ../_검증/2차_04_짧게.txt"""
import time

import pandas as pd

import 데이터읽기 as 읽기
import 포트폴리오 as 포

T0 = time.time()
공 = {**포.기본설정, "시장": ["KS"], "기준일": "마지막거래일", "재무주기": ("분기", "4분기합"),
      "제외": [("거래정지", {"아이템": 읽기.정지여부}), "관리종목"], "고르기": ("분위", 5), "비중": ["동일"], "거래비용": dict(수수료=0, 거래세=0, 슬리피지=0)}
판 = {"02": ({**공, "이름": "NH밸류", "리밸런싱": 1, "지표": [(m, "높게") for m in ["BP", "EP", "SP", "CFP", "EBITDA_EV"]], "합산": "z합산"},
             [("2002-03", "2005-02"), ("2016-06", "2018-05")]),
      "03": ({**공, "이름": "NH퀄리티로우볼", "리밸런싱": 3, "지표": [("ROE", "높게")]}, [("2002-03", "2005-02"), ("2016-10", "2018-09")])}
for 이름, (cfg, 기간들) in 판.items():
    for 기간 in 기간들:
        새 = 포.실행({**cfg, "기간": 기간, "재무시점": ("발표월말", 150)})["수익률"]
        옛 = 포.실행({**cfg, "기간": 기간, "재무시점": ("발표일", 150)})["수익률"]
        d = (새 - 옛).abs()
        print(f"{이름} {기간}: 모양 {새.shape}, 값 있는 칸 새 {int(새.notna().sum().sum())} / 옛 {int(옛.notna().sum().sum())}, 다른 칸 {int((d > 1e-12).sum().sum())}, 최대 차이 {d.max().max():.4f}", flush=True)
print(f"걸린 시간 {time.time() - T0:.0f}초")
