for k in (90, 150, 180):
    줄("6 발표일 없을 때", f"{k}일" + ("(지금)" if k == 150 else ""), "01 MF 확인판", 포.실행({**MF01, "재무시점": ("발표일", k)})["수익률"][("동일", "상위30")], F01)

