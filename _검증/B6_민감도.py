# 1. 재무 행 나이 상한(지금 2년)
원래재무 = 포.재무
def 재무_상한(t, how, 개월):
    f = 포.재무가능일(how)
    f = f[(f["가능일"] <= t) & ((f["결산일"] >= t - pd.DateOffset(months=개월)) if 개월 else True)]
    return f.sort_values(["회계연도", "결산일"]).drop_duplicates("코드", keep="last").set_index("코드")
for 판, m in {"12개월(t−1 회계연도만에 가까움)": 12, "18개월": 18, "24개월(지금)": 24, "제한 없음": None}.items():
    포.재무 = partial(재무_상한, 개월=m)
    줄("1 재무 나이 상한", 판, "01 MF", 포.실행(MF01)["수익률"][("동일", "상위30")], F01)
    줄("1 재무 나이 상한", 판, "확장 기준 EY+ROC 12개월", 포.실행(확장)["수익률"][("동일", "상위30")], F확장)
포.재무 = 원래재무

# 3. 단계별 남길 비율(지금 0.5) — 확장연구 단계별 두 순서, 12개월·동일
전략 = {f"{a}→{b} {k}": dict(지표=[(a, "높게", k), (b, "높게", 1.0)], 합산="단계별") for k in (0.2, 0.3, 0.5, 0.7) for a, b in (("EY", "ROC"), ("ROC", "EY"))}
