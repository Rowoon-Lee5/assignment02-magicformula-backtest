"""2차 진단 7(추가 지시 01:55): 04 신마법공식 — 2차 자료로 확인한 정의(PBR 순위 + GP/A 순위 합, 상위 30, 연 1회)와 2.0(시총 하위 20%에서 같은 규칙).
2차 자료(2026-11-05 02:30 받아 글자 확인): intelliquant.ai/article/573(1.0)·578(2.0), github sharebook-kr/quant_screener 02_·03_ screener.py.
판 목록은 돌리기 전에 정함(진행기록 02:3x). 숫자를 맞추려고 고르지 않고 돌린 판 전부 적음. 가중은 2차 자료에 없어 동일가중(04 본문과 같음).
  본문 1.0 = 04 노트북 설정(우동호 IMF 설정에 지표만 BP·GPA, 2004-04~2022-03, 4월 첫 거래일, 30종목)
  본문 2.0 = 1.0 + ('지표있음', BP·GPA) + ('시총분위', 1)(분위 모집단 = 지표 있는 종목, 01 본문과 같은 방식 — 2차 자료에 모집단 없음, 우리가 정함)
  K1 상위 50(책 'Top 50 25.44%' 2차 인용) / K2 GP/A > 0·자본 > 0만(github screener 조건 `(gp/a > 0) & (pbr > 0)`)
  K3 2.0 분위 모집단 = 남은 종목(지표있음 없이) / K4 기간 2002-07~2016-06·7월 첫 거래일(인텔리퀀트 글 '테스트기간: 2002년 7월 ~ 2016년 6월', 책 기간인지 글쓴이 기간인지 글로 구분 안 됨)
공통 폴더에서 PYTHONPATH=. python ../_검증/2차_07_신마법.py [--짧게] > ../_검증/2차_07_신마법_결과.txt"""
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

import 데이터읽기 as 읽기
import 종목거르기
import 지표
import 포트폴리오 as 포

T0 = time.time()
짧게 = "--짧게" in sys.argv
pd.set_option("display.width", 250); pd.set_option("display.max_columns", 30)


def GPA양수(s, c):  # github screener `df['gp/a'] > 0` (확인판 K2·K4에서만, 공통 코드 안 바꿈)
    v = 지표.GPA(s).reindex(c)
    return c[(v > 0).to_numpy()]


종목거르기.GPA양수 = GPA양수
기본 = {**포.우동호2023, "이름": "신마법공식", "기간": ("2004-04", "2022-03"), "끝": "마지막거래일", "지표": [("BP", "높게"), ("GPA", "높게")]}
소형 = [("지표있음", {"지표들": ["BP", "GPA"]}), ("시총분위", {"분위": 1})]
양수 = ["자본잠식", "GPA양수"]  # 자본잠식 = 자본총계 ≤ 0 제외 = PBR > 0
판 = {"본문 1.0": 기본, "본문 2.0": {**기본, "제외": 기본["제외"] + 소형},
     "K1 1.0 상위 50": {**기본, "고르기": ("상위N", 50)}, "K1 2.0 상위 50": {**기본, "제외": 기본["제외"] + 소형, "고르기": ("상위N", 50)},
     "K2 1.0 GP/A>0·자본>0": {**기본, "제외": 기본["제외"] + 양수}, "K2 2.0 GP/A>0·자본>0": {**기본, "제외": 기본["제외"] + 양수 + 소형},
     "K3 2.0 분위 모집단 = 남은 종목": {**기본, "제외": 기본["제외"] + [("시총분위", {"분위": 1})]}}
K4 = {"기간": ("2002-07", "2016-06")}  # 끝 = 2016-06 마지막 거래일(기본의 "끝")
판 |= {"K4 1.0 2002-07~2016-06 7월": {**기본, **K4}, "K4 2.0 2002-07~2016-06 7월": {**기본, **K4, "제외": 기본["제외"] + 소형}}
기간들 = {"앞": ("2004-04", "2006-04"), "뒤": ("2020-04", "2022-03")} if 짧게 else {"전": None}
rows = {}
for 이름, cfg in 판.items():
    for 구, 기간 in 기간들.items():
        c = {**cfg, "기간": 기간 or cfg["기간"]}
        if 짧게 and 이름.startswith("K4"):
            c["기간"] = {"앞": ("2002-07", "2004-07"), "뒤": ("2014-07", "2016-06")}[구]
        o = 포.실행(c)
        k = ("동일", f"상위{c['고르기'][1]}")
        r = o["수익률"][k].dropna()
        n = len(r); w = (1 + r).prod()
        rec = o["기록"]
        if 이름 == "본문 2.0":  # K3과 비교용: '지표있음' 단계에서 빠진 수(0이면 K3과 같은 판)
            앞열 = rec.columns[list(rec.columns).index("지표있음") - 1]
            print(f"  본문 2.0 {구}: '지표있음'에서 빠진 수 기준일별 {(rec[앞열] - rec['지표있음']).astype(int).tolist()} (앞 단계 '{앞열}')", flush=True)
        rows[(이름, 구)] = {"기간": f"{r.index[0]:%Y-%m}~{r.index[-1]:%Y-%m}", "개월": n, "누적(배)": w - 1, "연복리(CAGR)": w ** (12 / n) - 1,
                           "연 산술평균": r.mean() * 12, "편입 수 최소": int(rec[f"편입:{k[1]}"].min()), "편입 수 최대": int(rec[f"편입:{k[1]}"].max())}
        print(이름, 구, rows[(이름, 구)], f"{time.time() - T0:.0f}초", flush=True)
T = pd.DataFrame(rows).T
print("\n## 판 전부(동일가중, 우동호 거래비용·전량교체, 수정주가)\n", T.to_string())
print("\n2차 인용 숫자(쪽 미확인): 책 1.0 연 24.46%, 책 Top 50 25.44%(인텔리퀀트 573이 '할수있다 퀀트투자에서 테스트한 결과'로 인용). 인텔리퀀트 자체 시험: 1.0 28.83%, 2.0 37.29%(2002-07~2016-06), 2.0 2016-07 이후 19.66%, 1.0 2016 이후 -0.13%.")
if not 짧게:
    T.to_csv(Path(__file__).resolve().parent / "2차_07_신마법.csv", encoding="utf-8-sig")
print(f"걸린 시간 {time.time() - T0:.0f}초")
