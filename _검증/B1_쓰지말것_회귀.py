"""B단계 1번('쓰지 말 것' 판정 창 미래 정보) 회귀 검사. 예전 규칙(보유 구간 [t, 다음]을 보고 거름, 수익률 칸 그대로) 대 새 규칙
(기준일이 구간 (시작, 끝]에 들 때만 거름, 보유 중 걸린 칸만 TR 이상칸 → 가격수익률, 나머지 → 빈칸). 바뀐 칸이 모두 '쓰지 말 것' 종목인지 본다. 공통/에서 PYTHONPATH=. 로 실행."""
import pandas as pd
import 데이터읽기 as 읽기
import 포트폴리오 as 포
import 종목거르기

새거르기, 새칸 = 종목거르기.쓰지말것, 포.쓰지말것칸
def 예전거르기(s, c):
    b = 읽기.쓰지말것(s["가격"])
    return c[~c.isin(b.loc[(b["시작"] <= s["다음"]) & (b["끝"] >= s["t"]), "코드"])]

def 둘(cfg):
    종목거르기.쓰지말것, 포.쓰지말것칸 = 예전거르기, lambda R, item: R
    a = 포.실행(cfg)
    종목거르기.쓰지말것, 포.쓰지말것칸 = 새거르기, 새칸
    return a, 포.실행(cfg)

cfgs = {"01 MF(수정주가)": {**포.우동호2023, "기간": ("2004-04", "2022-03"), "끝": "마지막거래일"},
        "04 NM(TR, 6월)": {**포.기본설정, "시장": ["KS", "KQ"], "기간": ("2004-06", "2022-04"), "기준일": "마지막거래일", "리밸런싱": 12,
                           "재무시점": ("발표일", 150), "제외": ["금융업", "투자기구", ("지표있음", {"지표들": ["GPA", "BP"]}), ("시총상위", {"n": 500})],
                           "지표": [("GPA", "높게"), ("BP", "높게")], "고르기": ("분위", 3), "비중": ["동일", "시총"], "거래비용": dict(수수료=0, 거래세=0, 슬리피지=0)}}
for name, cfg in cfgs.items():
    a, b = 둘(cfg)
    flag = set(읽기.쓰지말것(cfg["가격"])["코드"])
    print(f"===== {name}")
    dn = (a["기록"]["쓰지말것"] - a["기록"]["시장"]) - (b["기록"]["쓰지말것"] - b["기록"]["시장"])
    print("거르기 단계에서 빠진 수 (예전 − 새), 0 아닌 기준일:", dn[dn != 0].to_dict())
    for k in a["보유"]:
        for t in a["보유"][k]:
            x, y = set(a["보유"][k][t].index), set(b["보유"][k][t].index)
            if x != y:
                print(f"  보유 바뀜 {k} {t:%Y-%m-%d}: 빠짐 {sorted(x - y)} 들어옴 {sorted(y - x)} / 들어온 것 중 '쓰지 말 것' 종목 {sorted((y - x) & flag)}")
    dR = (a["종목수익률"].fillna(9) != b["종목수익률"].fillna(9)).stack()
    dR = dR[dR]
    print("종목수익률 바뀐 칸:", len(dR), "/ 그중 '쓰지 말 것' 종목 아닌 칸:", sum(c not in flag for _, c in dR.index))
    for (d, c) in dR.index:
        print(f"  {d:%Y-%m-%d} {c}: {a['종목수익률'].at[d, c]:.4f} → {b['종목수익률'].at[d, c]:.4f}")
    dr = (a["수익률"] - b["수익률"]).abs()
    bad = dr.max(axis=1)
    print("포트폴리오 수익률 바뀐 달:", {f"{d:%Y-%m}": round(v, 6) for d, v in bad[bad > 0].items()})
    cum = lambda r: ((1 + r).prod() - 1).round(4).to_dict()
    print("누적 예전:", cum(a["수익률"]), "\n누적 새:", cum(b["수익률"]))
