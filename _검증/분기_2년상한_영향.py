"""추가 지시 K: 분기 재무 '분기말이 2년보다 오래된 행은 안 씀'(포트폴리오.분기재무) 규칙이 02·03에서 실제로 빼는 종목-기준일 수.
02·03 거르기(KS, 거래정지·관리종목 제외, 월말, 2002-03~2018-09)를 통과한 종목 중, 규칙이 없으면 쓸 분기 행이 있는데(가능일 ≤ t) 그 가장 최근 분기말이 t − 2년보다 이른 종목을 센다.
그 종목은 규칙이 있으면 분기 값이 빈칸이라 점수에서 빠진다. 공통/에서 PYTHONPATH=. 로 실행 → _검증/분기_2년상한_영향_결과.txt"""
import pandas as pd
import 데이터읽기 as 읽기
import 포트폴리오 as 포

cfg = {**포.기본설정, "시장": ["KS"], "기간": ("2002-03", "2018-09"), "기준일": "마지막거래일", "리밸런싱": 1, "재무시점": ("발표일", 150),
       "재무주기": ("분기", "4분기합"), "제외": [("거래정지", {"아이템": 읽기.정지여부}), "관리종목"]}
f = 포.분기가능일()
rows = []
for t in 포.기준일(cfg)[:-1]:
    _, c, _ = 포.거르기(t, cfg)
    끝 = f[f["가능일"] <= t].groupby("코드")["분기말"].max().reindex(c)
    빠짐 = 끝 < t - pd.DateOffset(years=2)
    rows.append({"기준일": t, "거른 종목": len(c), "분기 행 있음(제한 없을 때)": int(끝.notna().sum()), "2년 상한으로 빠짐": int(빠짐.sum()), "빠진 종목": ",".join(빠짐[빠짐].index)})
d = pd.DataFrame(rows).set_index("기준일")
print(f"기준일 {len(d)}개(월말 2002-03~2018-08), 거른 종목-기준일 {d['거른 종목'].sum()}, 분기 행 있음 {d['분기 행 있음(제한 없을 때)'].sum()}, 2년 상한으로 빠짐 {d['2년 상한으로 빠짐'].sum()}")
x = d[d["2년 상한으로 빠짐"] > 0]
print(f"빠진 종목이 있는 기준일 {len(x)}개, 기준일당 최대 {d['2년 상한으로 빠짐'].max()}, 서로 다른 종목 {len(set(','.join(x['빠진 종목']).split(',')) - {''})}")
print(x[["거른 종목", "2년 상한으로 빠짐", "빠진 종목"]].to_string(max_colwidth=120))
